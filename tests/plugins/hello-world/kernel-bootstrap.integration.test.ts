import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { generatePlugin } from "../../../src/plugins/plugin-builder/src/generate-plugin.js";
import { bootstrapKernel } from "../../../src/server/index.js";
import { isOk } from "../../../src/core/types.js";

/**
 * Feature #79 — "Reference hello-world plugin generated and proven to load
 * in the real kernel". `src/plugins/hello-world` (this suite's neighbor)
 * is the literal, unmodified output of feature #75's `create-plugin`
 * generator (`npm run create-plugin -- --id hello-world --description ...`,
 * see this plugin's own git history) — no hand-edits after scaffolding.
 * This suite proves the two things feature #79's steps actually require
 * beyond `tests/plugins/hello-world/manifest.test.ts`'s static
 * manifest-validation checks (which every generated plugin already gets
 * for free, per `plugin-templates.ts`'s `renderManifestTestTs`):
 *
 *   1. It loads successfully through the *real* kernel bootstrap
 *      (`bootstrapKernel()`, `src/server/index.ts` — the same path
 *      `tests/core/smoke.test.ts` drives against the real `src/plugins`
 *      tree) and shows up as `"loaded"` in `kernel.introspect()`'s report,
 *      alongside every other real, shipped plugin.
 *   2. Regenerating a plugin with the exact same id/description via
 *      `generatePlugin()` (into an isolated temp dir, never touching the
 *      real tree) produces byte-identical `plugin.json`/`index.ts`/
 *      `README.md` content to what's actually committed at
 *      `src/plugins/hello-world` — i.e. the committed plugin "loads
 *      without modification after regeneration": it is exactly, and
 *      only, what the generator produces today, not a hand-edited
 *      derivative of some earlier generator output.
 */

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const HELLO_WORLD_DIR = path.join(REPO_ROOT, "src", "plugins", "hello-world");

/**
 * Must match, verbatim, the `--description` the real `hello-world` plugin
 * was generated with (see its `index.ts`/`README.md` prose) — this is what
 * lets the regeneration in this suite reproduce the committed files
 * byte-for-byte rather than merely structurally.
 */
const HELLO_WORLD_DESCRIPTION =
  "Reference hello-world plugin: the minimal, complete example proven to load in the real " +
  "kernel bootstrap, generated by (and kept in sync with) the plugin-builder create-plugin " +
  "generator (feature #75).";

let tmpBaseDirs: string[] = [];

afterEach(() => {
  for (const dir of tmpBaseDirs) {
    rmSync(dir, { recursive: true, force: true });
  }
  tmpBaseDirs = [];
});

function freshRoots(): { pluginsRoot: string; testsRoot: string } {
  const base = mkdtempSync(path.join(tmpdir(), "appskeleton-hello-world-regen-"));
  tmpBaseDirs.push(base);
  return {
    pluginsRoot: path.join(base, "src-plugins"),
    testsRoot: path.join(base, "tests-plugins"),
  };
}

describe("hello-world — real kernel bootstrap", () => {
  it("loads successfully at kernel bootstrap and appears in kernel introspection as loaded", async () => {
    // Same real-tree, deterministic-env bootstrap path tests/core/smoke.test.ts
    // uses: no pluginsRoot override, so this scans and loads the actual
    // shipped src/plugins directory (hello-world included) exactly as a real
    // boot would.
    const kernel = await bootstrapKernel({ env: {} });
    try {
      const report = kernel.introspect();
      const helloWorld = report.plugins.find((plugin) => plugin.id === "hello-world");

      expect(helloWorld).toBeDefined();
      expect(helloWorld?.status).toBe("loaded");
      expect(helloWorld?.version).toBe("0.1.0");
      expect(helloWorld?.capabilities).toEqual({ provides: [], requires: [], granted: [] });
      expect(helloWorld?.error).toBeUndefined();
    } finally {
      await kernel.httpApp?.close();
    }
  });

  it("regenerating hello-world with generatePlugin() reproduces the committed files unmodified", async () => {
    const roots = freshRoots();

    const result = await generatePlugin({
      id: "hello-world",
      description: HELLO_WORLD_DESCRIPTION,
      pluginsRoot: roots.pluginsRoot,
      testsRoot: roots.testsRoot,
    });

    expect(isOk(result)).toBe(true);
    if (!isOk(result)) {
      return;
    }

    for (const fileName of ["plugin.json", "index.ts", "README.md"]) {
      const regenerated = readFileSync(
        path.join(roots.pluginsRoot, "hello-world", fileName),
        "utf-8",
      );
      const committed = readFileSync(path.join(HELLO_WORLD_DIR, fileName), "utf-8");
      expect(regenerated).toBe(committed);
    }

    const regeneratedGitkeep = readFileSync(
      path.join(roots.pluginsRoot, "hello-world", "src", ".gitkeep"),
      "utf-8",
    );
    const committedGitkeep = readFileSync(path.join(HELLO_WORLD_DIR, "src", ".gitkeep"), "utf-8");
    expect(regeneratedGitkeep).toBe(committedGitkeep);
  });
});
